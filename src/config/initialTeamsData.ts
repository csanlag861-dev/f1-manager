export function createInitialGameState(playerTeamId: string, managerName = 'Team Principal'): GameState {
  // Base tpRating based on initial team category (higher for top teams, lower for backmarkers)
  const team = INITIAL_TEAMS.find((t) => t.id === playerTeamId) ?? INITIAL_TEAMS[0];
  const initialTpRating = Math.round(team.reputation);

  return {
    managerProfile: {
      id: 'manager-1',
      name: managerName,
      tpRating: initialTpRating,
      seasonsCompleted: 0,
      trophyCabinet: {
        driversChampionships: 0,
        constructorsChampionships: 0,
        totalWins: 0,
        totalPodiums: 0,
      },
    },
    playerTeamId: team.id,
    season: {
      seasonNumber: 1,
      currentRaceIndex: 0,
      driverStandings: INITIAL_DRIVERS.map((d) => ({
        driverId: d.id,
        points: 0,
        wins: 0,
        podiums: 0,
      })),
      constructorStandings: INITIAL_TEAMS.map((t) => ({
        teamId: t.id,
        points: 0,
        wins: 0,
        podiums: 0,
      })),
    },
    teams: JSON.parse(JSON.stringify(INITIAL_TEAMS)),
    drivers: JSON.parse(JSON.stringify(INITIAL_DRIVERS)),
    chiefEngineers: JSON.parse(JSON.stringify(INITIAL_CHIEF_ENGINEERS)),
    cars: JSON.parse(JSON.stringify(INITIAL_CARS)),
    circuits: JSON.parse(JSON.stringify(OFFICIAL_CIRCUITS)),
    youthDrivers: generateYouthDriverPool(8, 1),
    lastRaceResult: null,
    updatedAt: new Date().toISOString(),
  };
}
